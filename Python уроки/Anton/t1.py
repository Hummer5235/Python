import turtle

t = turtle.Turtle() # Создать черепашку

t.screen.setup(800,800) # Создать экран с размерами 800*800

t.forward(100) # Вперед
t.left(90) # Влево
t.back(100) # Назад
t.right(90)
t.forward(100)
t.left(90)
t.forward(300)
t.left(90)
t.forward(100)








t.screen.exitonclick()
t.screen.mainloop() # Главный цикл