a = int(input('Введите число: '))
b = int(input('Введите число: '))
c = int(input('Введите число: '))

#Логическое И . Обязательно все условия
print(a>b and a>c)

#Логическое ИЛИ . Хотя бы одно из них
print(a>b or a>c)

#Логическое отрицание. Переворачиваем значение
print(not True)
print(not False)

