

# Мы всегда можем заменить цикл for с помощью цикла while. Следующие две программы выводят числа от 0 до 100:






# используем for
for i in range(101):
    print(i)


















# используем while
i = 0
while i < 101:
    print(i)
    i += 1













#Бесконечный цикл
count = 0 #Количество
while True :
    count= count + 1
    print('Выполняю повторение',count) 